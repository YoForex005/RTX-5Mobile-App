export const DEFAULT_LANGUAGE: LanguageCode = 'en';
export const SUPPORTED_LANGUAGE_CODES = new Set<LanguageCode>(SUPPORTED_LANGUAGES.map((language) => language.code));

export function isLanguageCode(value: unknown): value is LanguageCode {
  return typeof value === 'string' && SUPPORTED_LANGUAGE_CODES.has(value as LanguageCode);
}

export function normalizeLanguageCode(value: unknown): LanguageCode {
  return isLanguageCode(value) ? value : DEFAULT_LANGUAGE;
}

const TRANSLATABLE_ACCOUNT_CARD_NAMES = new Set(['Account', 'Standard', 'Demo', 'Real', 'Contest', 'Live']);

export function translateAccountCardName(name: string, t: (key: string) => string): string {
  const normalized = name.trim();

  if (TRANSLATABLE_ACCOUNT_CARD_NAMES.has(normalized)) {
    return t(normalized);
  }

  const accountWithSuffix = normalized.match(/^Account\s+(.+)$/);
  if (accountWithSuffix) {
    return `${t('Account')} ${accountWithSuffix[1]}`;
  }

  return name;
}

